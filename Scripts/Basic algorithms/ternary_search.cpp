li find_extremum(li l, li r) {
    while (l < r) {
        li m = l + (r - l) / 2;
        // <= левая граница минимума
        // < правая граница минимума
        // >= левая граница максимума
        // > правая граница максимума
        if (f(m) <= f(m + 1)) r = m;
        else l = m + 1;
    }
    return l;
}
