// Функции возвращают удвоенную неотрицательную площадь в long long.
// Координаты исходных точек по модулю не больше 10^9.
// Многоугольник должен быть простым, вершины перечисляются по границе.
// Выпуклость не требуется. Для вырожденных фигур площадь равна нулю.

long long doubledTriangleArea(const vec2d& A, const vec2d& B, const vec2d& C) {
    return abs((B - A) % (C - A));
}

long long doubledPolygonArea(const vector<vec2d>& v) {
    // Промежуточная сумма может быть больше итоговой площади.
    __int128 ans = 0;
    int size = (int)v.size();
    for (int i = 0; i < size; i++) {
        const vec2d& A = v[i];
        const vec2d& B = v[(i + 1) % size];
        ans += (__int128)(B.x - A.x) * (A.y + B.y);
    }
    // До взятия модуля: ans > 0 для обхода по часовой стрелке,
    // ans < 0 для обхода против часовой стрелки, ans == 0 при нулевой площади.
    if (ans < 0)
        ans = -ans;
    // Для простого многоугольника в квадрате [-10^9, 10^9]^2
    // удвоенная площадь не превосходит 8 * 10^18 и помещается в long long.
    return (long long)ans;
}
